CREATE TABLE fridge_shapes (
    fridge_id UUID PRIMARY KEY REFERENCES fridges (id) ON DELETE CASCADE,
    type TEXT NOT NULL CHECK (type IN ('MINIBAR', 'SINGLE_DOOR', 'TOP_FREEZER', 'BOTTOM_FREEZER', 'SIDE_BY_SIDE')),
    shelves INT NOT NULL CHECK (shelves BETWEEN 0 AND 6),
    door_racks INT NOT NULL CHECK (door_racks BETWEEN 0 AND 5),
    drawers INT NOT NULL CHECK (drawers BETWEEN 0 AND 3),
    freezer_shelves INT NOT NULL CHECK (freezer_shelves BETWEEN 0 AND 6),
    hinge TEXT NOT NULL CHECK (hinge IN ('LEFT', 'RIGHT')),
    width_cm INT NOT NULL CHECK (width_cm BETWEEN 20 AND 250),
    height_cm INT NOT NULL CHECK (height_cm BETWEEN 20 AND 250),
    depth_cm INT NOT NULL CHECK (depth_cm BETWEEN 20 AND 250),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

